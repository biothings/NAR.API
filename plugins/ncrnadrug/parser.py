def _parse_ccle(row):
    # NOTE: the "LncRNA" column in this file actually duplicates ENSEMBL_ID
    # (verified against raw rows), not a gene symbol/name — so the ncRNA's
    # display name is taken from SYMBOL, falling back to the Ensembl ID.
    # Similarly the "CCLE" column holds a drug alias/synonym used internally
    # by the CCLE drug-response panel (often identical to Drug_Name, but
    # sometimes a code name e.g. "OSI-906" for Linsitinib) — NOT a cell line
    # name, so it is modeled under `drug.ccle_alias`, not a cell-line object.
    ensembl_id = _clean(row.get("ENSEMBL_ID")) or _clean(row.get("LncRNA"))
    ncrna_name = _clean(row.get("SYMBOL")) or ensembl_id
    drug_name = _clean(row.get("Drug_Name"))
    ccle_alias = _clean(row.get("CCLE"))
    lnc_row = _clean(row.get("Lnc_Row"))
    composite = "_".join(
        _sanitize_id_part(x) for x in (ensembl_id, lnc_row, drug_name)
    )
    drug = _drug(row) or {}
    if ccle_alias:
        drug["ccle_alias"] = ccle_alias
    doc = {
        "relation": "drug_resistance",
        "evidence_tier": "predicted",
        "source_category": "DR_CCLE",
        "ncrna": {
            "name": ncrna_name,
            "type": "lncRNA",
            "symbol": _clean(row.get("SYMBOL")),
        },
        "drug": drug or None,
        "effect": _clean(row.get("Effect")),
        "detection_method": "CCLE expression profiling",
        "species": _clean(row.get("Species")),
        "tumor": _clean(row.get("Tumor")),
        "phenotype": _clean(row.get("Cancer")),
        "statistics": {
            "pvalue": _to_float(row.get("Pvalue")),
            "qvalue": _to_float(row.get("Qvalue")),
            "logfc": _to_float(row.get("logFC")),
            "effectsize": _to_float(row.get("EffectSize")),
        },
        "xrefs": _xrefs(row),
    }
    return composite, doc


