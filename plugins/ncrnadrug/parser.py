"""Parser for ncRNADrug (http://www.jianglab.cn/ncRNADrug/).

ncRNADrug provides two relation types, each split across a "Curated"
(experimentally validated) file and several "predicted" (computationally
derived) files. Critically, the seven bulk files do NOT share one common
schema — each predicted file was generated by a different pipeline (GEO
meta-analysis, NCI-60 drug-response panel, CCLE expression profiling,
Connectivity Map perturbation signatures) and exposes a different set of
statistics/columns. This parser normalizes all seven into one common
document shape (`ncrnadrug`), tagging each record with `relation`
(drug_resistance | drug_target) and `evidence_tier` (curated | predicted)
plus a `source_category` so consumers can filter/weight appropriately.

Files (relation, evidence_tier):
  DR_Curated.txt  -> drug_resistance, curated    (PMID-referenced)
  DR_GEO.txt      -> drug_resistance, predicted  (GEO meta-analysis)
  DR_NCI60.txt    -> drug_resistance, predicted  (NCI-60 cell line panel)
  DR_CCLE.txt     -> drug_resistance, predicted  (CCLE, lncRNA only)
  DT_Curated.txt  -> drug_target,    curated     (PMID-referenced)
  DT_GEO.txt      -> drug_target,    predicted   (GEO meta-analysis)
  DT_CMap.txt     -> drug_target,    predicted   (Connectivity Map)
"""

import csv
import os

from biothings.utils.dataload import dict_sweep, unlist


def _clean(value):
    """Return None for missing/NA sentinel values, else a stripped string."""
    if value is None:
        return None
    v = value.strip()
    if v == "" or v.upper() == "NA":
        return None
    return v


def _to_float(value):
    v = _clean(value)
    if v is None:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def _sanitize_id_part(value):
    """Make a raw field safe for use inside a composite _id."""
    if value is None:
        return "NA"
    return "_".join(str(value).split())


def _read_tsv(file_path):
    with open(file_path, "r", encoding="utf-8", errors="replace", newline="") as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        for row in reader:
            yield row


def _xrefs(row):
    xrefs = {}
    if v := _clean(row.get("DrugBank_ID")):
        xrefs["drugbank"] = v
    if v := _clean(row.get("CID")):
        xrefs["pubchem_cid"] = v
    if v := _clean(row.get("NSC")):
        xrefs["nsc"] = v
    if v := _clean(row.get("ENSEMBL_ID")):
        xrefs["ensembl_gene"] = v
    if v := _clean(row.get("NONCODE_ID")):
        xrefs["noncode"] = v
    if v := _clean(row.get("circBase_ID")):
        xrefs["circbase"] = v
    if v := _clean(row.get("DeepBase_ID")):
        xrefs["deepbase"] = v
    if v := _clean(row.get("CIRCpedia_ID")):
        xrefs["circpedia"] = v
    if v := _clean(row.get("miRBase_ID")):
        xrefs["mirbase"] = v
    return xrefs or None


def _drug(row):
    drug = {
        "name": _clean(row.get("Drug_Name")),
        "drugbank_id": _clean(row.get("DrugBank_ID")),
        "pubchem_cid": _clean(row.get("CID")),
        "nsc": _clean(row.get("NSC")),
        "fda_status": _clean(row.get("FDA")),
    }
    return {k: v for k, v in drug.items() if v is not None} or None


def _parse_dr_curated(row):
    ncrna_name = _clean(row.get("ncRNA_Name"))
    drug_name = _clean(row.get("Drug_Name"))
    ncrna_type = _clean(row.get("ncRNA_Type"))
    pmid = _clean(row.get("PMID"))
    composite = "_".join(
        _sanitize_id_part(x) for x in (pmid, ncrna_name, drug_name, ncrna_type)
    )
    doc = {
        "relation": "drug_resistance",
        "evidence_tier": "curated",
        "source_category": "DR_Curated",
        "ncrna": {
            "name": ncrna_name,
            "type": ncrna_type,
            "symbol": _clean(row.get("SYMBOL")),
            "target_gene": _clean(row.get("ncRNA_Target_Gene")),
        },
        "drug": _drug(row),
        "pathway": _clean(row.get("Pathway")),
        "effect": _clean(row.get("Effect")),
        "detection_method": _clean(row.get("Detection_Method")),
        "throughput": _clean(row.get("Throughput")),
        "species": _clean(row.get("Species")),
        "phenotype": _clean(row.get("Phenotype")),
        "condition": _clean(row.get("Condition")),
        "support": _clean(row.get("Support")),
        "pmid": int(pmid) if pmid and pmid.isdigit() else None,
        "published_year": _clean(row.get("Published_Year")),
        "xrefs": _xrefs(row),
    }
    return composite, doc


