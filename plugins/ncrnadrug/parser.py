# (filename, category, relation, row_parser)
_FILE_SPECS = [
    ("DR_Curated.txt", "DR_Curated", _parse_dr_curated),
    ("DR_GEO.txt", "DR_GEO", lambda row: _parse_geo(row, "drug_resistance", "DR_GEO")),
    ("DR_NCI60.txt", "DR_NCI60", _parse_nci60),
    ("DR_CCLE.txt", "DR_CCLE", _parse_ccle),
    ("DT_Curated.txt", "DT_Curated", _parse_dt_curated),
    ("DT_GEO.txt", "DT_GEO", lambda row: _parse_geo(row, "drug_target", "DT_GEO")),
    ("DT_CMap.txt", "DT_CMap", _parse_cmap),
]


def load_data(data_folder):
    """Parse all seven ncRNADrug bulk files and yield normalized documents.

    Each source file has its own column schema (see module docstring), so
    each is routed to a dedicated normalizer. `_id` is a composite built from
    the most specific identifying columns available in that file, prefixed by
    the source category to guarantee no cross-category collisions. Because a
    handful of predicted files lack a single unique key (e.g. the same
    ncRNA/drug pair re-tested in a different row), a `seen_ids` counter
    appends a numeric suffix to keep every _id unique; `on_duplicates: ignore`
    in the manifest is a safety net, not the primary dedup mechanism.
    """
    seen_ids = {}

    for fname, category, parse_row in _FILE_SPECS:
        fpath = os.path.join(data_folder, fname)
        if not os.path.exists(fpath):
            continue

        for row in _read_tsv(fpath):
            if not any(_clean(v) for v in row.values()):
                continue  # blank trailing line

            composite, fields = parse_row(row)
            base_id = f"{category}:{composite}"

            count = seen_ids.get(base_id, 0)
            seen_ids[base_id] = count + 1
            _id = base_id if count == 0 else f"{base_id}-{count + 1}"

            doc = {
                "_id": _id,
                "ncrnadrug": fields,
            }
            yield dict_sweep(unlist(doc), [None])
